export function getAudioUiText(
  value: string | null | undefined
) {
  return COPY[
    normalizeAudioUiLanguage(value)
  ];
}

export function getAudioSourceLanguageLabel(
  sourceLanguage:
    LectureSourceLanguage,
  appLanguage:
    string | null | undefined
) {
  const uiLanguage =
    normalizeAudioUiLanguage(
      appLanguage
    );

  if (
    sourceLanguage === 'en'
  ) {
    return uiLanguage === 'ua'
      ? 'Англійська'
      : uiLanguage === 'no'
        ? 'Engelsk'
        : 'English';
  }

  return uiLanguage === 'ua'
    ? 'Норвезька'
    : uiLanguage === 'no'
      ? 'Norsk'
      : 'Norwegian';
}

export function getAudioMarkerLabel(
  type:
    LectureMarkerType,
  appLanguage:
    string | null | undefined
) {
  const copy =
    getAudioUiText(
      appLanguage
    );

  switch (type) {
  case 'important':
    return copy.markerImportant;
  case 'unclear':
    return copy.markerUnclear;
  case 'repeat':
    return copy.markerRepeat;
  case 'term':
    return copy.markerTerm;
  default:
    return copy.markerImportant;
  }
}
