export type AudioUiLanguage =
  | 'ua'
  | 'en'
  | 'no';

export function normalizeAudioUiLanguage(
  value: string | null | undefined
): AudioUiLanguage {
  const language = String(value || '')
    .trim()
    .toLowerCase();

  if (
    language === 'no' ||
    language === 'nb'
  ) {
    return 'no';
  }

  if (language === 'en') {
    return 'en';
  }

  return 'ua';
}

